"""Generate the QueryCategory enum in Python and TypeScript.

Source: google-trends-categories.md, vendored verbatim from
https://github.com/pat310/google-trends-api/wiki/Google-Trends-Categories
(raw: https://raw.githubusercontent.com/wiki/pat310/google-trends-api/Google-Trends-Categories.md).

The source is a tree in which some categories appear under several parents. Each id maps to
exactly one name, so the enum has one member per unique id, in first-appearance order.
QUERY_CATEGORY_PARENTS keeps the hierarchy: id -> distinct parent ids, in source order
(the first is the one in its canonical path). The root, ALL_CATEGORIES (0), has no parents.
QUERY_CATEGORY_PATHS: id -> ids from the root down to it, at its first appearance in the source.
That is the id's canonical place in the hierarchy (path[1] is its top-level category).

Run from anywhere:  python3 lib/types/query-category/generate.py
"""

from __future__ import annotations

import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "google-trends-categories.md"
PY_OUT = HERE / "python" / "__init__.py"
TS_OUT = HERE / "typescript" / "index.ts"

LINE = re.compile(r"^ *\* (?P<name>.+): (?P<id>\d+)\s*$")


def member_name(name: str) -> str:
    s = name.replace("&", " and ").replace("+", " plus ")
    s = re.sub(r"[^A-Za-z0-9]+", "_", s).strip("_").upper()
    if s[0].isdigit():
        s = "_" + s
    return s


def parse() -> tuple[list[tuple[str, str, int]], dict[int, list[int]], dict[int, list[int]]]:
    seen: dict[int, str] = {}
    members: dict[str, int] = {}
    out: list[tuple[str, str, int]] = []
    parents: dict[int, list[int]] = {}
    paths: dict[int, list[int]] = {}
    stack: list[int] = []  # ids of the current path from the root
    for line in SOURCE.read_text().splitlines():
        m = LINE.match(line)
        if not m:
            continue
        name, cid = m["name"], int(m["id"])
        depth = (len(line) - len(line.lstrip(" "))) // 2
        stack = stack[:depth] + [cid]
        plist = parents.setdefault(cid, [])
        if depth > 0 and stack[depth - 1] not in plist:
            plist.append(stack[depth - 1])
        paths.setdefault(cid, list(stack))
        if cid in seen:
            if seen[cid] != name:
                raise ValueError(f"id {cid} has two names: {seen[cid]!r}, {name!r}")
            continue
        key = member_name(name)
        if key in members:
            raise ValueError(f"member {key} collides: ids {members[key]} and {cid}")
        seen[cid] = name
        members[key] = cid
        out.append((key, name, cid))
    if not out:
        raise ValueError(f"no categories parsed from {SOURCE}")
    return out, parents, paths


HEADER = "GENERATED by lib/types/query-category/generate.py. Do not edit by hand."


def render_py(
    rows: list[tuple[str, str, int]], parents: dict[int, list[int]], paths: dict[int, list[int]]
) -> str:
    members = "\n".join(f"    {k} = {cid}" for k, _, cid in rows)
    labels = "\n".join(f"    QueryCategory.{k}: {name!r}," for k, name, _ in rows)
    key = {cid: k for k, _, cid in rows}
    parent_lines = "\n".join(
        f"    QueryCategory.{k}: [{', '.join(f'QueryCategory.{key[p]}' for p in parents[cid])}],"
        for k, _, cid in rows
    )
    path_lines = "\n".join(
        f"    QueryCategory.{k}: [{', '.join(f'QueryCategory.{key[p]}' for p in paths[cid])}],"
        for k, _, cid in rows
    )
    return f'''# {HEADER}
"""Google Trends query categories. Values are the Google Trends category ids."""

from enum import IntEnum


class QueryCategory(IntEnum):
{members}


QUERY_CATEGORY_LABELS: dict[QueryCategory, str] = {{
{labels}
}}

# id -> distinct parent ids in source order; the first is canonical. Root has none.
QUERY_CATEGORY_PARENTS: dict[QueryCategory, list[QueryCategory]] = {{
{parent_lines}
}}

# id -> ids from the root down to it, at its first appearance (its canonical path).
QUERY_CATEGORY_PATHS: dict[QueryCategory, list[QueryCategory]] = {{
{path_lines}
}}

__all__ = ["QueryCategory", "QUERY_CATEGORY_LABELS", "QUERY_CATEGORY_PARENTS", "QUERY_CATEGORY_PATHS"]
'''


def render_ts(
    rows: list[tuple[str, str, int]], parents: dict[int, list[int]], paths: dict[int, list[int]]
) -> str:
    members = "\n".join(f"  {k}: {cid}," for k, _, cid in rows)
    labels = "\n".join(f"  [QueryCategory.{k}]: {_ts_str(name)}," for k, name, _ in rows)
    key = {cid: k for k, _, cid in rows}
    parent_lines = "\n".join(
        f"  [QueryCategory.{k}]: [{', '.join(f'QueryCategory.{key[p]}' for p in parents[cid])}],"
        for k, _, cid in rows
    )
    path_lines = "\n".join(
        f"  [QueryCategory.{k}]: [{', '.join(f'QueryCategory.{key[p]}' for p in paths[cid])}],"
        for k, _, cid in rows
    )
    return f"""// {HEADER}
// Google Trends query categories. Values are the Google Trends category ids.

export const QueryCategory = {{
{members}
}} as const;

export type QueryCategory = (typeof QueryCategory)[keyof typeof QueryCategory];

export const QUERY_CATEGORY_LABELS: Record<QueryCategory, string> = {{
{labels}
}};

// id -> distinct parent ids in source order; the first is canonical. Root has none.
export const QUERY_CATEGORY_PARENTS: Record<QueryCategory, readonly QueryCategory[]> = {{
{parent_lines}
}};

// id -> ids from the root down to it, at its first appearance (its canonical path).
export const QUERY_CATEGORY_PATHS: Record<QueryCategory, readonly QueryCategory[]> = {{
{path_lines}
}};
"""


def _ts_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    rows, parents, paths = parse()
    PY_OUT.write_text(render_py(rows, parents, paths))
    TS_OUT.write_text(render_ts(rows, parents, paths))
    print(f"wrote {len(rows)} categories to {PY_OUT.relative_to(HERE)} and {TS_OUT.relative_to(HERE)}")


if __name__ == "__main__":
    main()
